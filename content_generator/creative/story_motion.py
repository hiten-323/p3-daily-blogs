"""Premium 9:16 motion Story (≈10s MP4 + poster JPG) for Instagram Stories.

Replaces the pale single-colour static card. Layers (back → front):
  1. Rich coffee-tone gradient (espresso → roast → caramel glow) with film grain
  2. Slow-drifting warm light sweep + two parallax layers of soft bokeh
  3. Lit "plinth" floor with a natural contact shadow
  4. The TRUE-COLOUR approved jar cutout (no grading, no AI scene): only
     alpha-matted from its white studio sweep, scaled, gently pushed in.
     Fully in frame at every frame; never upscaled > 2x.
  5. Kinetic text: headline words rise in one by one, subline fades,
     a fact chip (Shopify-derived price) pops, then a pulsing follow CTA
     "Follow @purepantryprovisions" + "Shop at p3online.in".
Audio: an original procedurally generated lo-fi bed (see music_library/LICENSES.md,
CC0, generated by `story_bed()` below) — no third-party music.

All copy is checked with product_truth_findings before rendering; unsafe copy
falls back to verified SKU copy. Returns {"video", "poster", "qa"} or None.
"""
