# ── fonts ──────────────────────────────────────────────────────────────────
def _ffmpeg() -> str | None:
    """System ffmpeg, else the binary bundled with imageio-ffmpeg (a moviepy dep)."""
    exe = shutil.which("ffmpeg")
    if exe:
        return exe
    try:
        import imageio_ffmpeg
        return imageio_ffmpeg.get_ffmpeg_exe()
    except Exception:
        return None


def _font(kind: str, size: int):
    cands = {
        "serif": ["brand_assets/fonts/IBMPlexSerif-Bold.ttf", "/usr/share/fonts/truetype/dejavu/DejaVuSerif-Bold.ttf"],
        "italic": ["brand_assets/fonts/IBMPlexSerif-Italic.ttf", "/usr/share/fonts/truetype/dejavu/DejaVuSerif.ttf"],
        "sans": ["/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf",
                 "/usr/share/fonts/truetype/liberation/LiberationSans-Bold.ttf"],
    }[kind]
    for c in cands:
        try:
            return ImageFont.truetype(c, size)
        except Exception:
            continue
    return ImageFont.load_default()


def _ease(t: float) -> float:
    t = min(1.0, max(0.0, t))
    return 1 - (1 - t) ** 3


def _back(t: float) -> float:          # ease-out-back (overshoot pop)
    t = min(1.0, max(0.0, t)); c = 1.70158
    return 1 + (c + 1) * (t - 1) ** 3 + c * (t - 1) ** 2


# ── jar: true-colour cutout, alpha matte only ────────────────────────────────
def jar_cutout(it: dict) -> Image.Image:
    """RGBA jar with the studio sweep removed. Pixels inside the jar are untouched."""
    path = os.path.join(ap._DIR, it["file"])
    alpha_twin = path.replace(".png", "_alpha.png")
    if os.path.exists(alpha_twin):
        im = Image.open(alpha_twin).convert("RGBA")
    else:
        src = Image.open(path).convert("RGB")
        a = np.asarray(src)
        # Flood-fill the near-white studio sweep from every border pixel so
        # white label areas inside the jar stay opaque.
        is_bg = (a.min(axis=2) > 236) & ((a.max(axis=2) - a.min(axis=2)) < 14)
        h, w = is_bg.shape
        visited = np.zeros((h, w), dtype=bool)
        stack = [(0, x) for x in range(w)] + [(h - 1, x) for x in range(w)]
        stack += [(y, 0) for y in range(h)] + [(y, w - 1) for y in range(h)]
        while stack:
            y, x = stack.pop()
            if y < 0 or y >= h or x < 0 or x >= w or visited[y, x] or not is_bg[y, x]:
                continue
            visited[y, x] = True
            stack.extend(((y - 1, x), (y + 1, x), (y, x - 1), (y, x + 1)))
        # Dilate the flood a little so the cut edge sits outside the jar silhouette.
        from PIL import ImageFilter as _IF
        visit = Image.fromarray((visited * 255).astype(np.uint8)).filter(_IF.MaxFilter(5))
        jar_mask = Image.eval(visit, lambda v: 0 if v else 255).filter(_IF.MinFilter(3))
        jar_mask = jar_mask.filter(_IF.GaussianBlur(1.1))
        im = src.convert("RGBA"); im.putalpha(jar_mask)
    bb = im.getchannel("A").point(lambda v: 255 if v > 24 else 0).getbbox()
    return im.crop(bb) if bb else im


# ── background ─────────────────────────────────────────────────────────────
def _base_background(sku: str, seed: int) -> np.ndarray:
    rng = np.random.default_rng(seed)
    y = np.linspace(0, 1, H)[:, None]
    x = np.linspace(0, 1, W)[None, :]
    top = np.array([18, 10, 6], float); mid = np.array([62, 36, 20], float); low = np.array([36, 22, 13], float)
    accent = {"bold": (120, 64, 30), "purica": (150, 92, 44), "purista": (110, 58, 36),
              "ultra_blend": (140, 88, 40)}.get(sku, (130, 80, 40))
    g = np.where(y < 0.55, top + (mid - top) * (y / 0.55), mid + (low - mid) * ((y - 0.55) / 0.45))
    g = np.broadcast_to(g[:, None, :], (H, W, 3)).copy()
    # warm halo behind jar
    d = np.sqrt(((x - 0.5) * 1.25) ** 2 + ((y - 0.58) * 0.85) ** 2)
    glow = np.clip(1 - d / 0.62, 0, 1) ** 2.2
    g += glow[..., None] * (np.array(accent, float) - g * 0.35) * 0.9
    # vignette
    v = np.clip(1 - (np.sqrt((x - 0.5) ** 2 * 1.4 + (y - 0.5) ** 2) - 0.35) * 1.1, 0.55, 1)
    g *= v[..., None]
    # fine roast texture: blurred noise
    tex = Image.fromarray((rng.random((H // 4, W // 4)) * 255).astype(np.uint8)).resize((W, H), Image.BICUBIC)
    tex = np.asarray(tex.filter(ImageFilter.GaussianBlur(2)), float) / 255 - 0.5
    g += tex[..., None] * 10
    return np.clip(g, 0, 255)


def _bokeh_layer(seed: int, n: int, rmin: int, rmax: int, alpha: int) -> Image.Image:
    rng = np.random.default_rng(seed)
    lay = Image.new("RGBA", (W, H + 400), (0, 0, 0, 0)); d = ImageDraw.Draw(lay)
    for _ in range(n):
        r = int(rng.integers(rmin, rmax)); cx = int(rng.integers(0, W)); cy = int(rng.integers(0, H + 400))
        c = (255, int(rng.integers(190, 225)), int(rng.integers(120, 160)), int(alpha * rng.uniform(0.4, 1)))
        d.ellipse((cx - r, cy - r, cx + r, cy + r), fill=c)
    return lay.filter(ImageFilter.GaussianBlur(rmin * 0.8))


# ── copy ───────────────────────────────────────────────────────────────────
def _safe(text: str) -> bool:
    from content_generator.core.product_truth import product_truth_findings
    return bool(text) and not product_truth_findings(text) and "100%" not in text


def story_copy(sku: str, headline: str = "", sub: str = "") -> dict:
    from content_generator.core import price_truth as pt
    d_head, d_sub = ap.SKU_COPY.get(sku, ("Real coffee, honestly made.", "Pure instant coffee"))
    headline = ap._clean(headline) if headline else ""
    sub = ap._strip_shop(ap._clean(sub)) if sub else ""
    if not _safe(headline) or len(headline.split()) > 7:
        headline = d_head
    if not _safe(sub) or len(sub) > 60:
        sub = d_sub
    if sku == "ultra_blend":
        chip = f"Ultra Blend · about ₹{pt.ultra('per_cup')} a cup · {pt.ultra('cups')}+ cups"
    else:
        price = pt.variant_price(sku, 100)
        chip = f"{_SKU_NAME.get(sku, '')} 100g · ₹{int(price)}" if price else _SKU_FACT.get(sku, "")
    if not _safe(f"{_SKU_NAME.get(sku, '')} {chip}"):
        chip = _SKU_FACT.get(sku, "")
    return {"headline": headline, "sub": sub, "chip": chip,
            "cta": f"Follow {HANDLE}", "shop": "Shop at p3online.in"}


# ── audio ──────────────────────────────────────────────────────────────────
def story_bed(path: str, seconds: float = DURATION, sr: int = 44100, seed: int = 7) -> str:
    """Original lo-fi bed (CC0, generated here): Rhodes-ish chords, soft kick, brushed hats, crackle."""
    rng = np.random.default_rng(seed)
    n = int(seconds * sr); t = np.arange(n) / sr
    bpm = 84; beat = 60 / bpm
    chords = [[174.61, 220.0, 261.63, 329.63], [164.81, 196.0, 246.94, 293.66],
              [146.83, 174.61, 220.0, 261.63], [130.81, 164.81, 196.0, 246.94]]  # Fmaj7 Em7 Dm7 Cmaj7
    out = np.zeros(n)
    bar = beat * 4
    for i in range(int(seconds / bar) + 1):
        s0 = int(i * bar * sr); s1 = min(n, int((i + 1) * bar * sr))
        if s0 >= n:
            break
        tt = t[s0:s1] - t[s0]
        env = (1 - np.exp(-tt * 18)) * np.exp(-tt * 0.55)
        for f in chords[i % 4]:
            trem = 1 + 0.12 * np.sin(2 * np.pi * 4.6 * tt)
            out[s0:s1] += env * trem * (np.sin(2 * np.pi * f * tt) + 0.25 * np.sin(4 * np.pi * f * tt)) * 0.09
        bass = chords[i % 4][0] / 2
        out[s0:s1] += env * np.sin(2 * np.pi * bass * tt) * 0.16
    for k in range(int(seconds / beat) + 1):
        s0 = int(k * beat * sr)
        if s0 >= n:
            break
        L = min(n - s0, int(0.35 * sr)); tt = np.arange(L) / sr
        if k % 2 == 0:  # kick on 1 & 3
            out[s0:s0 + L] += np.sin(2 * np.pi * (50 + 70 * np.exp(-tt * 30)) * tt) * np.exp(-tt * 9) * 0.42
        else:           # soft snare/brush on 2 & 4
            out[s0:s0 + L] += rng.standard_normal(L) * np.exp(-tt * 22) * 0.07
        h0 = s0 + int(beat / 2 * sr); Lh = min(max(0, n - h0), int(0.05 * sr))
        if Lh > 0:
            out[h0:h0 + Lh] += rng.standard_normal(Lh) * np.exp(-np.arange(Lh) / sr * 90) * 0.035
    crack = (rng.random(n) > 0.9993) * rng.standard_normal(n) * 0.08 + rng.standard_normal(n) * 0.003
    out += crack
    # warm low-pass (one-pole) + fades
    a = 0.22; y = np.empty_like(out); acc = 0.0
    for i in range(n):
        acc += a * (out[i] - acc); y[i] = acc
    fade = np.minimum(1, np.minimum(t / 0.6, (seconds - t) / 1.2))
    y *= np.clip(fade, 0, 1)
    y = y / (np.abs(y).max() + 1e-9) * 0.78
    st = np.stack([y, np.roll(y, 220) * 0.96], 1)
    with wave.open(path, "wb") as wf:
        wf.setnchannels(2); wf.setsampwidth(2); wf.setframerate(sr)
        wf.writeframes((st * 32767).astype("<i2").tobytes())
    return path


# ── render ─────────────────────────────────────────────────────────────────
def _text_center(d, y, text, font, fill, alpha=255, shadow=True):
    w = d.textlength(text, font=font)
    x = (W - w) / 2
    if shadow:
        d.text((x + 2, y + 3), text, font=font, fill=(0, 0, 0, int(alpha * 0.45)))
    d.text((x, y), text, font=font, fill=fill[:3] + (alpha,))
    return w


def render_story_motion(sku: str, headline: str = "", sub: str = "", day: int = 0,
                        label: str = "story_motion", out_dir: str | None = None,
                        seconds: float = DURATION) -> dict | None:
    ffmpeg = _ffmpeg()
    if not ffmpeg:
        logger.warning("[story_motion] ffmpeg missing")
        return None
    pool = ap.items("ig_story", sku, ("real_photo", "cutout")) or ap.items(None, sku, ("cutout",))
    pool = [i for i in pool if i.get("type") in ("real_photo", "cutout")]
    if not pool:
        logger.warning("[story_motion] no approved cutout for %s", sku)
        return None
    pool.sort(key=lambda i: -(i.get("width", 0) * i.get("height", 0)))
    it = pool[0]
    jar = jar_cutout(it)
    copy = story_copy(sku, headline, sub)
    out_dir = out_dir or _OUT
    os.makedirs(out_dir, exist_ok=True)

    # jar geometry: ~50% of frame height, inside safe zones, never > 2x upscale
    target_h = int(H * 0.47)
    s = min(target_h / jar.height, (W * 0.72) / jar.width, 2.0)
    jar_base = jar.resize((round(jar.width * s), round(jar.height * s)), Image.LANCZOS)
    floor_y = int(H * 0.78)

    base = _base_background(sku, seed=day + 11)
    base_img = Image.fromarray(base.astype(np.uint8)).convert("RGBA")
    # lit plinth floor
    fl = Image.new("RGBA", (W, H), (0, 0, 0, 0)); fd = ImageDraw.Draw(fl)
    fd.ellipse((-W * 0.25, floor_y - 70, W * 1.25, floor_y + 360), fill=(196, 140, 84, 60))
    fl = fl.filter(ImageFilter.GaussianBlur(60))
    base_img.alpha_composite(fl)
    far = _bokeh_layer(day + 3, 26, 10, 26, 70)
    near = _bokeh_layer(day + 5, 9, 34, 70, 55)
    grain_rng = np.random.default_rng(day)
    grains = [Image.fromarray(np.clip(128 + grain_rng.normal(0, 9, (H // 2, W // 2)), 0, 255).astype(np.uint8))
              .resize((W, H)).convert("L") for _ in range(4)]

    f_head = _font("serif", 92); f_sub = _font("italic", 44); f_chip = _font("sans", 38)
    f_cta = _font("sans", 46); f_shop = _font("sans", 40); f_brand = _font("sans", 30)
    probe = ImageDraw.Draw(Image.new("RGBA", (10, 10)))
    words = copy["headline"].split()
    lines, cur = [], []
    for w_ in words:
        trial = " ".join(cur + [w_])
        if probe.textlength(trial, font=f_head) > W * 0.84 and cur:
            lines.append(cur); cur = [w_]
        else:
            cur.append(w_)
    if cur:
        lines.append(cur)
    lines = lines[:3]

    audio = story_bed(os.path.join(out_dir, f"{label}_bed.wav"), seconds)
    video = os.path.join(out_dir, f"{label}.mp4")
    cmd = [ffmpeg, "-y", "-loglevel", "error", "-f", "rawvideo", "-pix_fmt", "rgb24", "-s", f"{W}x{H}",
           "-r", str(FPS), "-i", "-", "-i", audio, "-c:v", "libx264", "-preset", "medium", "-crf", "18",
           "-pix_fmt", "yuv420p", "-c:a", "aac", "-b:a", "160k", "-shortest", "-movflags", "+faststart", video]
    proc = subprocess.Popen(cmd, stdin=subprocess.PIPE)
    frames = int(seconds * FPS)
    poster_t = seconds * 0.78
    poster = None
    jar_boxes = []
    try:
        for fi in range(frames):
            t = fi / FPS
            img = base_img.copy()
            # light sweep
            sweep = Image.new("L", (W, H), 0); sd = ImageDraw.Draw(sweep)
            sx = -400 + (W + 800) * ((t / seconds) % 1.0)
            sd.polygon([(sx, 0), (sx + 260, 0), (sx - 340, H), (sx - 600, H)], fill=26)
            sweep = sweep.filter(ImageFilter.GaussianBlur(90))
            img = Image.composite(Image.new("RGBA", (W, H), (255, 214, 160, 255)), img, sweep)
            # parallax bokeh
            img.alpha_composite(far, (0, -int(200 + 30 * t)))
            img.alpha_composite(near, (int(14 * math.sin(t * 0.7)), -int(120 + 75 * t)))
            # jar: rise in, slow push-in, gentle float
            e = _ease((t - 0.15) / 1.1)
            zoom = 1.0 + 0.045 * (t / seconds)
            jw, jh = round(jar_base.width * zoom), round(jar_base.height * zoom)
            jimg = jar_base.resize((jw, jh), Image.LANCZOS) if zoom > 1.001 else jar_base
            float_y = 6 * math.sin(t * 1.6)
            jx = (W - jw) // 2
            jy = int(floor_y - jh + (1 - e) * 120 + float_y)
            # contact shadow
            sh = Image.new("RGBA", (W, H), (0, 0, 0, 0)); shd = ImageDraw.Draw(sh)
            shd.ellipse((jx + jw * 0.08, floor_y - 18, jx + jw * 0.92, floor_y + 34), fill=(8, 4, 2, int(170 * e)))
            img.alpha_composite(sh.filter(ImageFilter.GaussianBlur(18)))
            if e > 0:
                j = jimg.copy()
                if e < 1:
                    j.putalpha(j.getchannel("A").point(lambda v, k=e: int(v * k)))
                img.alpha_composite(j, (jx, jy))
            jar_boxes.append((jx, jy, jx + jw, jy + jh))
            # film grain (soft-light-ish)
            g = grains[fi % 4]
            img = Image.blend(img, Image.merge("RGBA", (g, g, g, Image.new("L", (W, H), 255))), 0.035)
            d = ImageDraw.Draw(img)
            # brand kicker
            ka = int(255 * _ease((t - 0.3) / 0.6))
            _text_center(d, _SAFE_TOP - 70, "PURITY BEANS", f_brand, _GOLD, ka, shadow=False)
            # kinetic headline: word-by-word rise
            y = _SAFE_TOP + 10
            k = 0
            for ln in lines:
                total = probe.textlength(" ".join(ln), font=f_head)
                x = (W - total) / 2
                for w_ in ln:
                    p = _ease((t - 0.7 - 0.14 * k) / 0.5)
                    if p > 0:
                        dy = (1 - p) * 40
                        d.text((x + 2, y + dy + 4), w_, font=f_head, fill=(0, 0, 0, int(110 * p)))
                        d.text((x, y + dy), w_, font=f_head, fill=_CREAM + (int(255 * p),))
                    x += probe.textlength(w_ + " ", font=f_head)
                    k += 1
                y += 104
            # gold rule + subline
            pr = _ease((t - 0.9 - 0.14 * k) / 0.6)
            if pr > 0:
                rw = int(160 * pr); d.rounded_rectangle(((W - rw) / 2, y + 12, (W + rw) / 2, y + 17), 3, fill=_GOLD + (255,))
                _text_center(d, y + 36, copy["sub"], f_sub, (236, 214, 180), int(255 * pr))
            # fact chip pop (Shopify-derived figure)
            pc = _back((t - 3.2) / 0.5) if t < 6.8 else max(0.0, 1 - (t - 6.8) / 0.35)
            if pc > 0.01 and copy["chip"]:
                tw = d.textlength(copy["chip"], font=f_chip)
                cw, chh = (tw + 70) * pc, 78 * pc
                cx, cy = W / 2, floor_y + 70
                d.rounded_rectangle((cx - cw / 2, cy, cx + cw / 2, cy + chh), int(chh / 2),
                                    fill=(246, 236, 214, int(235 * min(1, pc))))
                if pc > 0.85:
                    d.text((cx - tw / 2, cy + 18), copy["chip"], font=f_chip, fill=_ESPRESSO + (255,))
            # follow CTA
            pf = _back((t - 6.9) / 0.55)
            if pf > 0.01:
                pulse = 1 + 0.03 * math.sin((t - 6.9) * 6) if t > 7.5 else 1
                tw = d.textlength(copy["cta"], font=f_cta)
                cw, chh = (tw + 90) * pf * pulse, 96 * pf * pulse
                cx, cy = W / 2, floor_y + 52
                d.rounded_rectangle((cx - cw / 2, cy, cx + cw / 2, cy + chh), int(chh / 2), fill=_GOLD + (255,))
                if pf > 0.85:
                    d.text((cx - tw / 2, cy + (chh - 52) / 2), copy["cta"], font=f_cta, fill=_ESPRESSO + (255,))
                _text_center(d, cy + chh + 28, copy["shop"], f_shop, _CREAM, int(255 * _ease((t - 7.4) / 0.5)))
            frame = img.convert("RGB")
            if poster is None and t >= poster_t:
                poster = frame.copy()
            proc.stdin.write(frame.tobytes())
        proc.stdin.close(); rc = proc.wait(timeout=300)
    except Exception as exc:
        logger.warning("[story_motion] render failed: %s", exc)
        proc.kill(); return None
    if rc != 0 or not os.path.exists(video):
        return None
    poster_path = os.path.join(out_dir, f"{label}_poster.jpg")
    (poster or frame).save(poster_path, quality=93)
    qa = qa_story(jar_boxes, video, copy)
    if qa:
        logger.error("[story_motion] QA failed: %s", qa)
        try:
            os.remove(video)
        except OSError:
            pass
        return {"video": None, "poster": poster_path, "qa": qa, "copy": copy}
    return {"video": video, "poster": poster_path, "qa": [], "copy": copy, "source_jar": it["file"]}


def qa_story(jar_boxes, video: str, copy: dict) -> list[str]:
    """Fail-closed: jar fully in frame every frame, duration/size/audio OK, copy safe."""
    issues = []
    for (x0, y0, x1, y1) in jar_boxes[int(FPS * 1.4):]:
        if x0 < 0 or y0 < 0 or x1 > W or y1 > H:
            issues.append("jar_out_of_frame"); break
        if y0 < _SAFE_TOP + 100:
            issues.append("jar_under_headline"); break
    if not shutil.which("ffprobe"):
        # bundled ffmpeg has no ffprobe: trust the render parameters we wrote
        dur = len(jar_boxes) / FPS
        if not 7.5 <= dur <= 15:
            issues.append(f"duration_{dur:.1f}s")
        meta = None
    try:
        import json
        if not shutil.which("ffprobe"):
            raise StopIteration
        meta = json.loads(subprocess.check_output(
            ["ffprobe", "-v", "quiet", "-print_format", "json", "-show_streams", "-show_format", video]))
        dur = float(meta["format"]["duration"])
        if not 7.5 <= dur <= 15:
            issues.append(f"duration_{dur:.1f}s")
        kinds = {s["codec_type"] for s in meta["streams"]}
        if "audio" not in kinds:
            issues.append("no_audio")
        v = [s for s in meta["streams"] if s["codec_type"] == "video"][0]
        if (int(v["width"]), int(v["height"])) != (W, H):
            issues.append("not_9x16")
    except StopIteration:
        pass
    except Exception as exc:
        issues.append(f"probe_failed:{exc}")
    for key in ("headline", "sub", "chip"):
        if copy.get(key) and not _safe(copy[key]):
            issues.append(f"unsafe_copy_{key}")
    if HANDLE not in copy.get("cta", "") or "p3online.in" not in copy.get("shop", ""):
        issues.append("cta_missing")
